"""2019 고3 3월모의고사 나형 29번 — 파라미터 솔버 (수동 작성).
문제: 자연수 m. '3×2^m 이 첫째항 3, 공비가 2 이상 자연수인 등비수열의 제k항'이
      되게 하는 모든 자연수 k 의 합을 A(m). 예) A(2)=3+2=5. A(200)? (답 477)
구조: 3×2^m = 3·r^{k-1} → r^{k-1}=2^m. r≥2 자연수 → r=2^j (j≥1), j(k-1)=m.
      ⇒ k-1 은 m 의 양의 약수 d, k=d+1. 따라서 A(m)=Σ_{d|m}(d+1)=σ(m)+τ(m).
      검산: A(2): 약수 {1,2} → (1+1)+(2+1)=5 ✓.  A(200)=465+12=477.
재생산: m 파라미터화 (약수합 구조).
"""
import sympy as sp


def A(m):
    return sum(d + 1 for d in sp.divisors(m))    # = σ(m) + τ(m)


CANDIDATE = 477
assert A(2) == 5, A(2)                            # 문제 예시로 구조 자체 검증
assert A(200) == CANDIDATE, A(200)
print('VERIFY_PASS')
