"""
2021 고1 9월모의고사 30번
이차함수 최댓값/최솟값 조건으로 함수 g(a) 정의

f(x) = x² - 4x - 10a, [a, a³]에서 최댓값/최솟값의 합 = g(a)
g(a) 구간별:
  [0, 3/2]: g(t) = -7t² + 14t + 9
  [3/2, 3]: g(t) = -7t² + 20t
  t≥3: g(t) = -6t² + 14t + 9

g(a) = 4b의 해가 4개 ⟺ 81/4 < 4b < 144/7
p = 81/4, q = 144/7
4p + 7q = 81 + 144 = 225
"""

def solve():
    # p = 81/4, q = 144/7
    # 4p + 7q = 4×(81/4) + 7×(144/7) = 81 + 144
    p = 81 / 4
    q = 144 / 7
    result = 4 * p + 7 * q
    return int(result)

if __name__ == '__main__':
    print(f"답: {solve()}")
