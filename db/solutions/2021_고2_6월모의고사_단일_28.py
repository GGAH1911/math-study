"""
2021 고2 6월모의고사 28번
로그함수와 좌표기하: 외분점 조건

외분점 P가 곡선 위에 있음 → b = 3(a+1)
격자점 집합 합=25 조건 → 4 ≤ b/a < 8

4a ≤ 3(a+1) < 8a
4a ≤ 3a + 3 < 8a
a ≤ 3, 3 < 5a
a ∈ {1, 2, 3}

b = 3(a+1)이므로:
  a=1: b=6, a+b=7
  a=2: b=9, a+b=11
  a=3: b=12, a+b=15 (최댓값)
"""

def solve():
    # a = 3일 때 최대
    # b = 3(3+1) = 12
    # a + b = 3 + 12 = 15
    a = 3
    b = 3 * (a + 1)
    result = a + b
    return result

if __name__ == '__main__':
    print(f"답: {solve()}")
