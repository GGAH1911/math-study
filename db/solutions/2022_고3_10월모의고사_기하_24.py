import numpy as np

# 원래 타원: x^2/16 + y^2/8 = 1, 기울기 2인 접선의 y절편 검증
a2, b2, m = 16, 8, 2

# 접선 y = 2x + c 가 타원에 접하는 조건: c^2 = a^2*m^2 + b^2
c_squared = a2 * m**2 + b2  # = 64 + 8 = 72
c = np.sqrt(c_squared)  # = 6*sqrt(2)

# 두 접선 y = 2x + c 와 y = 2x - c 를 타원에 대입해 판별식 = 0 확인
# y = 2x + c 대입: x^2/16 + (2x+c)^2/8 = 1
# x^2/16 + (4x^2 + 4cx + c^2)/8 = 1
# 8x^2/128 + (4x^2 + 4cx + c^2)*2/16... 정리:
# 16x^2/16 + 2*(4x^2+4cx+c^2)/16 * 2 => 다시 계산
# x^2/16 + (2x+c)^2/8 = 1
# 8x^2 + 16*(2x+c)^2 = 128  ... *128
# 8x^2 + 16*(4x^2 + 4cx + c^2) = 128
# 8x^2 + 64x^2 + 64cx + 16c^2 = 128
# 72x^2 + 64cx + 16c^2 - 128 = 0
# 판별식 D = (64c)^2 - 4*72*(16c^2-128)
D = (64*c)**2 - 4*72*(16*c_squared - 128)
# c^2 = 72 이므로
D_val = (64**2)*c_squared - 4*72*(16*c_squared - 128)
D_val_num = (64**2)*72 - 4*72*(16*72 - 128)
D_val_num2 = 72*(64**2 - 4*(16*72 - 128))
inner = 64**2 - 4*(16*72-128)
# = 4096 - 4*(1152-128) = 4096 - 4*1024 = 4096 - 4096 = 0
if abs(inner) < 1e-9:
    # 접선 확인됨
    # y절편: A=(0, c), B=(0, -c)
    AB = 2*c
    expected = 12*np.sqrt(2)
    if abs(AB - expected) < 1e-9:
        print('VERIFY_PASS')
    else:
        print('VERIFY_FAIL')
else:
    print('VERIFY_FAIL')
