"""2019 고3 3월모의고사 나형 4번 — 파라미터 솔버 (수동 작성).
문제: 그림의 함수 f:X→X (X={1,2,3,4,5}) 에 대하여 (f∘f)(3). (답 ⑤ = 5)
그림 판독(대응): f(1)=4, f(2)=5, f(3)=2, f(4)=1, f(5)=3  (db/raw 원본 이미지 확대 판독).
구조: (f∘f)(x)=f(f(x)). f(3)=2, f(2)=5 → 5.
재생산: 대응표 f 와 질의 x 를 바꾸면 동종 문제 무한 생성.
"""


def solve(f, x):
    return f[f[x]]


F = {1: 4, 2: 5, 3: 2, 4: 1, 5: 3}      # 그림에서 읽은 대응
CANDIDATE = 5                            # 보기 ⑤ 의 값
assert solve(F, 3) == CANDIDATE, solve(F, 3)
print('VERIFY_PASS')
