"""
2025 고1 3월모의고사 단일 25번
직육면체: 부피 조건과 합의 배수 조건으로 겉넓이 계산

조건:
- 직육면체 가로 a, 세로 b, 높이 c (자연수)
- 부피 abc = 33
- a + b + c가 7의 배수

풀이:
1. 33 = 3 × 11의 약수 조합
   가능한 (a, b, c): (1, 1, 33), (1, 3, 11), (1, 11, 3), (1, 33, 1), (3, 1, 11), (3, 11, 1), (11, 1, 3), (11, 3, 1), (33, 1, 1)

2. a + b + c가 7의 배수인 경우만 선택
   - (1, 1, 33): 1+1+33 = 35 = 7×5 ✓
   - (1, 33, 1): 1+33+1 = 35 = 7×5 ✓
   - (33, 1, 1): 33+1+1 = 35 = 7×5 ✓

3. 모두 같은 조합 (1, 1, 33) → 겉넓이 = 2(ab + bc + ca) = 2(1 + 33 + 33) = 134
"""

def solve():
    # 부피 = 33, 약수는 1, 3, 11, 33
    # 조건: a + b + c ≡ 0 (mod 7)

    # 가능한 모든 (a, b, c) 조합
    candidates = []
    for a in [1, 3, 11, 33]:
        for b in [1, 3, 11, 33]:
            if 33 % (a * b) == 0:
                c = 33 // (a * b)
                if (a + b + c) % 7 == 0:
                    candidates.append((a, b, c))

    # 예제: (1, 1, 33)
    a, b, c = 1, 1, 33

    # 겉넓이 = 2(ab + bc + ca)
    surface_area = 2 * (a*b + b*c + c*a)

    return surface_area

if __name__ == '__main__':
    print(f"답: {solve()}")
