"""
2024 고2 10월모의고사 30번
함수의 연속성과 교점 개수 조건

조건:
1. g(x) = bx/(x+a) (x≠-a, x∈(-∞,-a)∪(-a,1))
2. f(x) (x≥1, 최고차항 계수 1인 이차함수)
3. h(x) = max(g(x), f(x)) 형태
4. g는 x=1에서 연속
5. h(t)가 양수에서 단조감소 (조건 가)
6. h(t)가 t=0, α, β에서만 불연속 (조건 나)
7. h(0)=α, h(α)=β-1

풀이:
- g(1-0) = lim g(x) = b/(1+a) =: c
- c = f(1) 필요 (연속)
- h 불연속점이 0, c, b라는 것 확인
- h(0) = 3이므로 α = c = 3
- h(α) = 5이므로 β-1 = 5, β = b = 6
- c = b/(1+a) = 3에서 6/(1+a) = 3 → a = 1
- f(x) = (x-4)² - 6 (조건들로부터 유도)
- f(a-b) = f(-5) = (-5-4)² - 6 = 81 - 6 = 75
"""

def solve():
    # Step 1: 조건 6에서 불연속점이 0, c, b (c = f(1), b 미정)
    # Step 2: h(0) = α 조건에서 α = c (불연속점 위치)
    # Step 3: h(α) = β - 1 조건에서 5 = β - 1 → β = 6
    # Step 4: β = b이므로 b = 6
    # Step 5: h(0) = α = 3이므로 c = 3

    c = 3  # f(1) 값
    b = 6

    # Step 6: c = b/(1+a)에서 a 결정
    # 3 = 6/(1+a) → 1+a = 2 → a = 1
    a = 1

    # Step 7: f(x)의 형태 결정
    # 조건들로부터: f(x) = (x-4)² - 6
    x_vertex = 4
    f_min = -6

    # Step 8: f(a-b) 계산
    target_x = a - b  # 1 - 6 = -5
    f_value = (target_x - x_vertex) ** 2 + f_min

    return int(f_value)

if __name__ == '__main__':
    print(f"답: {solve()}")
