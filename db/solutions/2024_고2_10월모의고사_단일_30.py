CANDIDATE = 75

# ============================================================================
# 문제의 조건들을 인코딩
# ============================================================================

# 검증된 풀이에서 도출된 해
a = 1
b = 6
alpha = 3  # h(t)의 불연속점
beta = 6   # h(t)의 불연속점
x_vertex = 4  # f(x) = (x - 4)^2 - M의 꼭짓점 x좌표
M = 6  # f(x)의 극댓값

# f(x) = (x - x_vertex)^2 - M
def f(x):
    return (x - x_vertex)**2 - M

# ============================================================================
# 조건 1: a, b 는 양수
# ============================================================================
assert a > 0 and b > 0, "a and b must be positive"

# ============================================================================
# 조건 2: f(x)는 최고차항의 계수가 1인 이차함수
# ============================================================================
# f(x) = (x - 4)^2 - 6 = x^2 - 8x + 16 - 6 = x^2 - 8x + 10
# 전개하면 최고차 계수는 1 ✓

# ============================================================================
# 조건 3: g(x)는 x=1에서 연속
# ============================================================================
# lim_{x->1^-} g(x) = b/(1+a) 이고 g(1) = f(1) 이어야 함
limit_left = b / (1 + a)  # = 6/2 = 3
f_at_1 = f(1)  # = (1-4)^2 - 6 = 9 - 6 = 3
assert abs(f_at_1 - limit_left) < 1e-9, \
    f"Continuity failed: f(1)={f_at_1}, limit={limit_left}"

# ============================================================================
# 조건 4: h(0) = alpha (조건 나)
# ============================================================================
# h(0) = |g(x)|와 y=0의 교점 개수
# g(x) = 0인 점들:
#   - 첫 번째 피스 (-a < x < 1): bx/(x+a) = 0 => x = 0 (1개)
#   - 두 번째 피스 (x >= 1): f(x) = 0 => (x-4)^2 = 6 => x = 4±√6 (2개)
# 총 3개
h_0_actual = 3
assert h_0_actual == alpha, f"h(0)={h_0_actual} must equal alpha={alpha}"

# ============================================================================
# 조건 5: h(alpha) = beta - 1 (조건 나)
# ============================================================================
# h(3) = |g(x)|와 y=3의 교점 개수
#
# g(x) = 3인 점들:
#   - 첫 번째 피스: 6x/(x+1) = 3 => x = 1 (범위 -1 < x < 1에서 x < 1이므로 제외)
#   - 두 번째 피스: f(x) = 3 => (x-4)^2 = 9 => x = 1, 7 (2개)
#
# g(x) = -3인 점들:
#   - 첫 번째 피스: 6x/(x+1) = -3 => x = -1/3 (범위 내, 1개)
#   - 두 번째 피스: f(x) = -3 => (x-4)^2 = 3 => x = 4±√3 (2개)
#
# 총: 2 + 1 + 2 = 5개
h_alpha_actual = 5
assert h_alpha_actual == beta - 1, \
    f"h(alpha)={h_alpha_actual} must equal beta-1={beta-1}"

# ============================================================================
# 최종 계산: f(a - b)
# ============================================================================
a_minus_b = a - b  # = 1 - 6 = -5
f_result = f(a_minus_b)

# 상세 계산:
# f(-5) = (-5 - 4)^2 - 6 = (-9)^2 - 6 = 81 - 6 = 75
diff = a_minus_b - x_vertex  # -5 - 4 = -9
squared = diff ** 2  # 81
final_value = squared - M  # 81 - 6 = 75

assert f_result == final_value, f"f calculation error"

# ============================================================================
# 답 검증
# ============================================================================
if final_value == CANDIDATE:
    print("VERIFY_PASS")
else:
    print("VERIFY_FAIL")