"""
2024 고3 7월모의고사 공통 20번
함수 h(x) = max(f(x), g(x))와 직선 y=k의 교점 조건

f(x) = x³ - 12x, 극값: f(-2)=16 (극대), f(2)=-16 (극소)
g(x) = a(x-2) + 2 (직선, 점 (2,2)을 지남)

h(x) = k가 4개 해를 가지는 조건:
  - a > 0: 불가능
  - a < 0: 2-4a < 16 ⟹ a > -3.5

범위: -3.5 < a < 0
10(M-m) = 10 × (0 - (-3.5)) = 10 × 3.5 = 35
"""

def solve():
    # m = -3.5, M = 0
    m = -3.5
    M = 0

    result = 10 * (M - m)

    return int(result)

if __name__ == '__main__':
    print(f"답: {solve()}")
