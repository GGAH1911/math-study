"""
2025 고2 6월모의고사 단일 30번
로그 부등식과 진수 조건: 0이 아닌 정수 k의 합

조건:
(가) log_{2^k}(f(2)+|k|) ≤ log_{2^k}8, f(x)=-(x-1)²
(나) log_{2^k}(f(x)+|k|(x-1)) ≤ log_{2^k}(4x)를 만족하는 자연수 x의 개수 = 6

풀이:
1. f(2) = -1 → 조건 (가): log_{2^k}(|k|-1) ≤ log_{2^k}8
2. 진수 조건: |k| ≥ 2
3. k>0: |k|-1 ≤ 8 → k ∈ {2,...,9}
4. k<0: |k|-1 ≥ 8 → k ≤ -9

5. 조건 (나) 변환 (t = x-1):
   - k>0 (밑>1): t²-(k-4)t+4 ≥ 0인 t의 개수 = 6
   - k<0 (밑∈(0,1)): t²-(|k|-4)t+4 ≤ 0인 t의 개수 = 6

6. k>0 케이스:
   - k=7: 판별식<0 → 모든 t에서 조건 만족, 도메인 {1,...,6} → 개수=6 ✓
   - k=9: 일부 t에서만 조건 만족, 도메인에서 개수=6 ✓

7. k<0 케이스:
   - k=-11: 도메인 {1,...,6}에서 개수=6 ✓

8. 최종: k ∈ {7, 9, -11}
   답: 7 + 9 + (-11) = 5
"""

def solve():
    # 조건을 만족하는 k 값들
    # 상세 계산 결과: k ∈ {7, 9, -11}

    k_values = [7, 9, -11]

    # 합 계산
    result = sum(k_values)

    return result

if __name__ == '__main__':
    print(f"답: {solve()}")
