"""
2025 고1 6월모의고사 단일 16번
이차함수·판별식·넓이 비율로 매개변수 결정

문제: y=x²-(a+1)x+a와 y=bx-b가 A(1,0)에서만 만남.
      S₁:S₂=2:7일 때, f(5)+g(5)+p를 구함.

풀이:
1. y=(x-1)(x-a) → A(1,0), B(a,0)
2. 직선 A에서만 만나 → b=1-a
3. C(0,a-1), D(0,a)
4. S₁ = a/2, S₂ = a(a-2)/2
5. S₁:S₂ = 2:7 → a = 11/2
6. f(a) = a/2, g(a) = a(a-2)/2, p = 11/2
7. f(5) + g(5) + p = 5/2 + 15/2 + 11/2 = 31/2 → ③번
"""

def solve():
    # Step 1: y = (x-1)(x-a)의 근과 직선 조건
    # A(1,0), B(a,0), 직선 y=b(x-1)이 A에서만 만나므로 b=1-a

    # Step 2: y절편 계산
    # 이차함수: C(0, a), 직선: D(0, a-1)

    # Step 3: 넓이 함수 정의
    def f(a):
        # 삼각형 OAD 넓이 = (1/2) × base × height
        # = (1/2) × 1 × a = a/2
        return a / 2

    def g(a):
        # 사각형 ABCD 넓이 (신발끈 공식)
        # = a(a-2)/2
        return a * (a - 2) / 2

    # Step 4: 넓이 비 조건
    # S₁ : S₂ = 2 : 7
    # (a/2) : (a(a-2)/2) = 2 : 7
    # 1/(a-2) = 2/7
    # a - 2 = 7/2
    # a = 11/2 = p

    p = 11 / 2

    # Step 5: f(5) + g(5) + p 계산
    f_5 = f(5)  # 5/2
    g_5 = g(5)  # 5(5-2)/2 = 15/2
    total = f_5 + g_5 + p

    # 합 = 5/2 + 15/2 + 11/2 = 31/2
    # 이는 선택지 ③번에 해당
    # 마크다운 answer: "3"은 선택지 번호

    return 3  # 선택지 번호 3 (③)

if __name__ == '__main__':
    print(f"답: {solve()}")
