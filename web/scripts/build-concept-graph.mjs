#!/usr/bin/env node
/**
 * Parse all concept frontmatter under ../docs/concepts and emit
 * src/data/concept-graph.json with nodes (mastery, type, dagre coords)
 * and edges (prerequisite arrows).
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';
import matter from 'gray-matter';
import dagre from 'dagre';

const __dirname = dirname(fileURLToPath(import.meta.url));
const WEB_ROOT = dirname(__dirname);
const DOCS_DIR = join(WEB_ROOT, '..', 'docs', 'concepts');
const OUT_DIR = join(WEB_ROOT, 'src', 'data');
const OUT_FILE = join(OUT_DIR, 'concept-graph.json');
const SUMMARIES_FILE = join(OUT_DIR, 'concept-summaries.json');

// Extract a 1-line summary from the markdown body. Used by /concepts cards
// so a reader knows what a concept is without clicking through. We pick the
// first non-empty plain prose paragraph — skipping headings, code fences,
// list markers, blockquotes, KaTeX display blocks, HTML tags, stub
// placeholder text, and bold-only section labels.
const SUMMARY_MAX = 200;
// Stubs generated by ingest carry this filler line. It says nothing useful
// and would otherwise dominate the card grid, so we treat it as "no summary".
const PLACEHOLDER_RE = /^\(.*학습 시 채워집니다.*\)\s*$/;
// Bold-only section labels like `**정의(definition)**` or `*보조정리*` are
// markup for body structure, not actual content. Detected as a line that
// is entirely a single bold/italic span with no surrounding prose.
const BOLD_ONLY_RE = /^(\*{1,2}|_{1,2})[^*_]+\1\s*$/;
function extractSummary(body) {
  if (!body) return null;
  const lines = body.split('\n');
  let inFence = false;
  let inMath = false;
  const buf = [];
  const flush = () => {
    if (!buf.length) return null;
    const text = buf.join(' ').replace(/\s+/g, ' ').trim();
    if (!text) { buf.length = 0; return null; }
    buf.length = 0;
    if (PLACEHOLDER_RE.test(text)) return null;
    return text;
  };
  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith('```')) { inFence = !inFence; const t = flush(); if (t) return truncate(t); continue; }
    if (inFence) continue;
    if (line.startsWith('$$')) { inMath = !inMath; const t = flush(); if (t) return truncate(t); continue; }
    if (inMath) continue;
    if (!line) { const t = flush(); if (t) return truncate(t); continue; }
    if (line.startsWith('#')) continue;
    if (line.startsWith('>')) continue;
    if (line.startsWith('---')) continue;
    if (/^[-*+]\s/.test(line)) continue;
    if (/^\d+\.\s/.test(line)) continue;
    if (line.startsWith('<')) continue;
    if (BOLD_ONLY_RE.test(line)) continue;
    if (PLACEHOLDER_RE.test(line)) continue;
    buf.push(line);
  }
  const t = flush();
  return t ? truncate(t) : null;
}
function truncate(s) {
  if (s.length <= SUMMARY_MAX) return s;
  // Cut at a sentence/word boundary near the limit so we don't slice mid-character.
  const cut = s.slice(0, SUMMARY_MAX);
  const lastPunct = Math.max(cut.lastIndexOf('. '), cut.lastIndexOf('다. '), cut.lastIndexOf('. '));
  if (lastPunct > SUMMARY_MAX * 0.6) return cut.slice(0, lastPunct + 1).trim() + '…';
  const lastSpace = cut.lastIndexOf(' ');
  return (lastSpace > SUMMARY_MAX * 0.6 ? cut.slice(0, lastSpace) : cut).trim() + '…';
}

// sub-dir 호환: 'algebra/근의_공식' (DOCS_DIR 기준 relative path, .md 제거).
// NFC 정규화: 일부 한글 파일명이 디스크에 NFD(자모 분리)로 저장돼 있는데
// Node readdir 은 그대로 보존하는 반면 Astro content collection 은 NFC 로
// 정규화한다. 정규화를 안 맞추면 /concepts 가 graph 의 home_unit 과
// collection 항목을 join 하지 못해 스포크가 "기타" 로 떨어진다.
function slugFromFile(absPath) {
  return relative(DOCS_DIR, absPath).replace(/\.md$/, '').split(/[\\/]/).join('/').normalize('NFC');
}
// frontmatter cross-ref ('docs/concepts/algebra/근의_공식.md' 또는 슬러그 only) → slug
function slugFromRef(p) {
  return p.replace(/^docs\/concepts\//, '').replace(/\.md$/, '').normalize('NFC');
}

function walkMd(dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...walkMd(p));
    else if (e.name.endsWith('.md')) out.push(p);
  }
  return out;
}

function readConcepts() {
  const concepts = [];
  const summaries = {};
  for (const filePath of walkMd(DOCS_DIR)) {
    const parsed = matter(readFileSync(filePath, 'utf-8'));
    const fm = parsed.data;
    const id = slugFromFile(filePath);
    const summary = extractSummary(parsed.content);
    if (summary) summaries[id] = summary;
    concepts.push({
      id,
      slug: id,
      label: (id.split('/').pop() ?? id).replace(/_/g, ' '),
      concept_type: fm.concept_type ?? 'definition',
      grade: fm.grade ?? null,
      domain: fm.domain ?? null,
      unit: fm.unit ?? null,
      subunit: fm.subunit ?? null,
      mastery: fm.mastery ?? 'unknown',
      prerequisites: (fm.prerequisites ?? []).map(slugFromRef),
      enables: (fm.enables ?? []).map(slugFromRef),
      review_state: fm.review_state ?? null,
      next_review: fm.next_review ?? null,
    });
  }
  return { concepts, summaries };
}

// Assign each spoke to its owning unit. The file path is authoritative:
// docs/concepts/<domain>/<grade>/<unit>/<spoke>.md means <unit> owns the
// spoke, so the path parent is the home unit. The prerequisite chain is a
// *learning* dependency and may point at a different unit (or break), which
// is exactly what scattered spokes into the wrong domain's "기타" bucket —
// so we only walk it as a fallback for legacy/flat nodes whose path parent
// isn't a unit.
function annotateHomeUnit(concepts) {
  const byId = new Map(concepts.map((c) => [c.id, c]));
  const cache = new Map();
  function resolve(id, seen = new Set()) {
    if (cache.has(id)) return cache.get(id);
    if (seen.has(id)) return null;
    seen.add(id);
    const n = byId.get(id);
    if (!n) return null;
    if (n.concept_type === 'unit') { cache.set(id, id); return id; }
    for (const ref of n.prerequisites ?? []) {
      const r = resolve(ref, seen);
      if (r) { cache.set(id, r); return r; }
    }
    cache.set(id, null);
    return null;
  }
  for (const c of concepts) {
    if (c.concept_type === 'unit') { c.home_unit = c.id; continue; }
    // 1순위: 파일 경로 부모가 unit 노드면 그것.
    const parentId = c.id.includes('/') ? c.id.slice(0, c.id.lastIndexOf('/')) : null;
    const parent = parentId ? byId.get(parentId) : null;
    if (parent && parent.concept_type === 'unit') { c.home_unit = parentId; continue; }
    // 2순위(폴백): 경로 부모가 단원이 아닌 레거시 노드는 prereq 체인으로.
    c.home_unit = resolve(c.id);
  }
}

function buildEdges(concepts) {
  const ids = new Set(concepts.map((c) => c.id));
  const edges = [];
  for (const c of concepts) {
    for (const pre of c.prerequisites) {
      if (ids.has(pre)) {
        edges.push({ id: `e-${pre}-${c.id}`, source: pre, target: c.id });
      }
    }
  }
  return edges;
}

function layout(concepts, edges) {
  const g = new dagre.graphlib.Graph();
  g.setGraph({ rankdir: 'LR', nodesep: 30, ranksep: 120, marginx: 30, marginy: 30 });
  g.setDefaultEdgeLabel(() => ({}));
  for (const c of concepts) {
    g.setNode(c.id, { width: 180, height: 70 });
  }
  for (const e of edges) {
    g.setEdge(e.source, e.target);
  }
  dagre.layout(g);
  const positioned = concepts.map((c) => {
    const n = g.node(c.id);
    return { ...c, x: n.x, y: n.y };
  });
  return positioned;
}

function detectCycles(concepts) {
  const adj = new Map(concepts.map((c) => [c.id, c.enables.filter((e) => concepts.find((cc) => cc.id === e))]));
  const indeg = new Map(concepts.map((c) => [c.id, 0]));
  for (const [_, outs] of adj) for (const t of outs) indeg.set(t, (indeg.get(t) ?? 0) + 1);
  const queue = [];
  for (const [id, d] of indeg) if (d === 0) queue.push(id);
  let visited = 0;
  while (queue.length) {
    const n = queue.shift();
    visited++;
    for (const t of adj.get(n) ?? []) {
      indeg.set(t, indeg.get(t) - 1);
      if (indeg.get(t) === 0) queue.push(t);
    }
  }
  return concepts.length - visited;
}

function main() {
  const { concepts, summaries } = readConcepts();
  annotateHomeUnit(concepts);
  const edges = buildEdges(concepts);
  const positioned = layout(concepts, edges);
  const cycles = detectCycles(concepts);

  const byMastery = { unknown: 0, learning: 0, proficient: 0, mastered: 0 };
  for (const c of concepts) byMastery[c.mastery] = (byMastery[c.mastery] ?? 0) + 1;
  const byType = { unit: 0, definition: 0, theorem: 0, lemma: 0, example: 0 };
  for (const c of concepts) byType[c.concept_type] = (byType[c.concept_type] ?? 0) + 1;
  const byGrade = {};
  for (const c of concepts) if (c.grade) byGrade[c.grade] = (byGrade[c.grade] ?? 0) + 1;
  const byDomain = {};
  for (const c of concepts) if (c.domain) byDomain[c.domain] = (byDomain[c.domain] ?? 0) + 1;

  const out = {
    generatedAt: new Date().toISOString(),
    nodes: positioned,
    edges,
    stats: {
      nodes: concepts.length,
      edges: edges.length,
      cycles,
      byMastery,
      byType,
      byGrade,
      byDomain,
    },
  };

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, JSON.stringify(out, null, 2), 'utf-8');
  writeFileSync(
    SUMMARIES_FILE,
    JSON.stringify({ generatedAt: out.generatedAt, summaries }, null, 2),
    'utf-8',
  );
  const summaryCount = Object.keys(summaries).length;
  console.log(`[concept-graph] ${concepts.length} nodes, ${edges.length} edges, ${cycles} cycles → ${OUT_FILE}`);
  console.log(`[concept-summaries] ${summaryCount}/${concepts.length} concepts have a body summary → ${SUMMARIES_FILE}`);
}

main();
